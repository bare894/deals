// tests fall back to PGlite — real Postgres compiled to WASM, in-process, no server needed.
//
// Queries keep `?` placeholders (converted to $1, $2 …) and are called as
//   await db.get(sql, ...params)   → first row or undefined
//   await db.all(sql, ...params)   → rows
//   await db.run(sql, ...params)   → { changes, rows }   (add RETURNING id to get new ids)
// Inside tx(db, fn) every db call made by fn — however deeply nested — runs on that
// transaction's connection (AsyncLocalStorage), and nested tx() calls join the outer one.
