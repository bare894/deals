/** `?` → `$n`, skipping quoted strings/identifiers. Cached: the SQL texts are a fixed set. */
const pgSqlCache = new Map();
function toPgSql(sql) {
  let out = pgSqlCache.get(sql);
  if (out) return out;
  let n = 0;
  let quote = null;
  out = '';
  for (const ch of sql) {
    if (quote) {
      if (ch === quote) quote = null;
    } else if (ch === "'" || ch === '"') quote = ch;
    else if (ch === '?') {
      out += `$${++n}`;
      continue;
    }
    out += ch;
  }
  pgSqlCache.set(sql, out);
  return out;
}

const txStore = new AsyncLocalStorage();

class Db {
  /** @param driver {{ query(text, params): Promise<{rows, rowCount}>, exec(text), transaction(fn), close() }} */
  constructor(driver, kind) {
    this.driver = driver;
    this.kind = kind;
  }

  async query(sql, params) {
    const conn = txStore.getStore() || this.driver;
    return conn.query(toPgSql(sql), params);
  }

  async get(sql, ...params) {
    return (await this.query(sql, params)).rows[0];
  }

  async all(sql, ...params) {
    return (await this.query(sql, params)).rows;
  }

  async run(sql, ...params) {
    const r = await this.query(sql, params);
    return { changes: r.rowCount, rows: r.rows };
  }

  /** Multi-statement SQL with no parameters (schema). */
  async exec(sql) {
    const conn = txStore.getStore() || this.driver;
    return conn.exec(sql);
  }

  async tx(fn) {
    if (txStore.getStore()) return fn();
    return this.driver.transaction((conn) => txStore.run(conn, fn));
  }

  /**
   * Run fn so that a failing statement (e.g. an expected unique violation) can be caught
   * without aborting the surrounding transaction.
   */
  async savepoint(fn) {
    if (!txStore.getStore()) return fn();
    await this.exec('SAVEPOINT sp');
    try {
      const result = await fn();
      await this.exec('RELEASE SAVEPOINT sp');
      return result;
    } catch (err) {
      await this.exec('ROLLBACK TO SAVEPOINT sp');
      throw err;
    }
  }

  close() {
    return this.driver.close();
  }
}

async function pgDriver(url) {
  const { default: pg } = await import('pg');
  pg.types.setTypeParser(INT8, Number); // BIGINT timestamps/prices/counts fit in a JS number
  const pool = new pg.Pool({ connectionString: url, max: Number(process.env.PG_POOL_MAX || 10) });
  pool.on('error', (err) => console.error('[db] idle client error:', err.message));
  const wrap = (c) => ({ query: (text, params) => c.query(text, params), exec: (text) => c.query(text) });
  return {
    ...wrap(pool),
    async transaction(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const result = await fn(wrap(client));
        await client.query('COMMIT');
        return result;
      } catch (err) {
        await client.query('ROLLBACK').catch(() => {});
        throw err;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
  };
}

async function pgliteDriver(dataDir) {
  let PGlite;
  try {
    ({ PGlite } = await import('@electric-sql/pglite'));
  } catch {
    throw new Error('DATABASE_URL is not set and the local Postgres (PGlite) is not installed. Run `npm install`, or set DATABASE_URL.');
  }
  if (dataDir) mkdirSync(dataDir, { recursive: true });
  const pg = new PGlite(dataDir, { parsers: { [INT8]: Number } });
  await pg.waitReady;
  const wrap = (c) => ({
    query: async (text, params) => {
      const r = await c.query(text, params);
      return { rows: r.rows, rowCount: r.affectedRows ?? r.rows.length };
    },
    exec: (text) => c.exec(text),
  });
  return { ...wrap(pg), transaction: (fn) => pg.transaction((t) => fn(wrap(t))), close: () => pg.close() };
}

/**
 * Open the database and bring the schema up to date.
 * `target`: a postgres:// URL, a directory for local PGlite data, or null for in-memory PGlite (tests).
 */
export async function openDb(target) {
  const isUrl = typeof target === 'string' && /^postgres(ql)?:\/\//.test(target);
  const db = new Db(isUrl ? await pgDriver(target) : await pgliteDriver(target || undefined), isUrl ? 'postgres' : 'pglite');
  await migrate(db);
  return db;
}

export async function migrate(db) {
  await db.tx(async () => {
    // Serialize concurrent boots (e.g. two replicas starting at once).
    await db.exec('SELECT pg_advisory_xact_lock(727274)');
    await db.exec('CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, applied_at BIGINT NOT NULL)');
    const { v } = await db.get('SELECT COALESCE(MAX(version), 0) AS v FROM schema_migrations');
    for (let i = v; i < MIGRATIONS.length; i++) {
      await db.exec(MIGRATIONS[i]);
      await db.run('INSERT INTO schema_migrations (version, applied_at) VALUES (?, ?)', i + 1, Date.now());
      console.log(`[db] applied migration ${i + 1}`);
    }
  });
}

/** Drop everything (npm run seed). */
export async function resetDb(db) {
  await db.exec(`DROP TABLE IF EXISTS ${TABLES.join(', ')} CASCADE`);
  await migrate(db);
}

export function tx(db, fn) {
  return db.tx(fn);
}

