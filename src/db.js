export function slugify(name) {
  return String(name).toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

export async function ensureCategories(db) {
  const { n } = await db.get('SELECT COUNT(*) AS n FROM categories');
  if (n === 0) {
    for (const name of DEFAULT_CATEGORIES) await db.run('INSERT INTO categories (name, slug) VALUES (?, ?) ON CONFLICT DO NOTHING', name, slugify(name));
  }
}
